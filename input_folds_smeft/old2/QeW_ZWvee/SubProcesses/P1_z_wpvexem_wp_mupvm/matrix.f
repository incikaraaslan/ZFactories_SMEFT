C     By the MadGraph5_aMC@NLO Development Team
C     Visit launchpad.net/madgraph5 and amcatnlo.web.cern.ch
C     
C     MadGraph5_aMC@NLO for Madevent Version
C     
C     Returns amplitude squared summed/avg over colors
C     and helicities
C     for the point in phase space P(0:3,NEXTERNAL)
C     
C     Process: z > w+ ve~ e- @1
C     *   Decay: w+ > mu+ vm NPcHe=0 NPcHl1=0 NPcHl3=0 NPceB=0 NPceH=0
C      NPceW<=1
C     
      USE DISCRETESAMPLER
      IMPLICIT NONE
C     
C     CONSTANTS
C     
      INCLUDE '../../Source/vector.inc'
      INCLUDE 'genps.inc'
      INCLUDE 'maxconfigs.inc'
      INCLUDE 'nexternal.inc'
      INCLUDE 'maxamps.inc'
      INCLUDE 'run.inc'
      INTEGER                 NCOMB
      PARAMETER (             NCOMB=48)
      INTEGER    NGRAPHS
      PARAMETER (NGRAPHS=130)
      INTEGER    NDIAGS
      PARAMETER (NDIAGS=130)
      INTEGER    THEL
      PARAMETER (THEL=NCOMB)
C     
C     ARGUMENTS 
C     
      REAL*8 P(0:3,NEXTERNAL),ANS
      REAL*8 RHEL, RCOL
      INTEGER DUM, SELECTED_HEL, SELECTED_COL, IVEC
C     
C     global (due to reading writting)
C     
      LOGICAL GOODHEL(NCOMB)
      INTEGER NTRY
      COMMON/BLOCK_GOODHEL/NTRY,GOODHEL
      INTEGER NB_SPIN_STATE(2)
      DATA  NB_SPIN_STATE /3,0/
      COMMON /NB_HEL_STATE/ NB_SPIN_STATE
C     
C     LOCAL VARIABLES 
C     
      INTEGER NHEL(NEXTERNAL,NCOMB)
      REAL*8 T,MATRIX
      REAL*8 R,SUMHEL,TS(NCOMB)
      INTEGER I,IDEN
      INTEGER IPROC,JC(NEXTERNAL),II
      REAL*8 HWGT, XTOT, XTRY, XREJ, XR, YFRAC(0:NCOMB)
      INTEGER IDUM, NGOOD, J, JJ
      REAL     XRAN1
      EXTERNAL XRAN1

C     
C     GLOBAL VARIABLES
C     
      DOUBLE PRECISION AMP2(MAXAMPS), JAMP2(0:MAXFLOW)
      COMMON/TO_AMPS/  AMP2,       JAMP2

C     CHARACTER*101        HEL_BUFF
C     COMMON/TO_HELICITY/  HEL_BUFF

      REAL*8 POL(2)
      COMMON/TO_POLARIZATION/ POL

      INTEGER          ISUM_HEL
      LOGICAL                    MULTI_CHANNEL
      COMMON/TO_MATRIX/ISUM_HEL, MULTI_CHANNEL
      INTEGER MAPCONFIG(0:LMAXCONFIGS), ICONFIG
      COMMON/TO_MCONFIGS/MAPCONFIG, ICONFIG
      DATA IDUM /-1/
      DATA XTRY, XREJ, NGOOD /0,0,0/
      SAVE YFRAC

      DATA (NHEL(I,   1),I=1,5) /-1, 1,-1, 1,-1/
      DATA (NHEL(I,   2),I=1,5) /-1, 1,-1, 1, 1/
      DATA (NHEL(I,   3),I=1,5) /-1, 1,-1,-1,-1/
      DATA (NHEL(I,   4),I=1,5) /-1, 1,-1,-1, 1/
      DATA (NHEL(I,   5),I=1,5) /-1, 1, 1, 1,-1/
      DATA (NHEL(I,   6),I=1,5) /-1, 1, 1, 1, 1/
      DATA (NHEL(I,   7),I=1,5) /-1, 1, 1,-1,-1/
      DATA (NHEL(I,   8),I=1,5) /-1, 1, 1,-1, 1/
      DATA (NHEL(I,   9),I=1,5) /-1,-1,-1, 1,-1/
      DATA (NHEL(I,  10),I=1,5) /-1,-1,-1, 1, 1/
      DATA (NHEL(I,  11),I=1,5) /-1,-1,-1,-1,-1/
      DATA (NHEL(I,  12),I=1,5) /-1,-1,-1,-1, 1/
      DATA (NHEL(I,  13),I=1,5) /-1,-1, 1, 1,-1/
      DATA (NHEL(I,  14),I=1,5) /-1,-1, 1, 1, 1/
      DATA (NHEL(I,  15),I=1,5) /-1,-1, 1,-1,-1/
      DATA (NHEL(I,  16),I=1,5) /-1,-1, 1,-1, 1/
      DATA (NHEL(I,  17),I=1,5) / 0, 1,-1, 1,-1/
      DATA (NHEL(I,  18),I=1,5) / 0, 1,-1, 1, 1/
      DATA (NHEL(I,  19),I=1,5) / 0, 1,-1,-1,-1/
      DATA (NHEL(I,  20),I=1,5) / 0, 1,-1,-1, 1/
      DATA (NHEL(I,  21),I=1,5) / 0, 1, 1, 1,-1/
      DATA (NHEL(I,  22),I=1,5) / 0, 1, 1, 1, 1/
      DATA (NHEL(I,  23),I=1,5) / 0, 1, 1,-1,-1/
      DATA (NHEL(I,  24),I=1,5) / 0, 1, 1,-1, 1/
      DATA (NHEL(I,  25),I=1,5) / 0,-1,-1, 1,-1/
      DATA (NHEL(I,  26),I=1,5) / 0,-1,-1, 1, 1/
      DATA (NHEL(I,  27),I=1,5) / 0,-1,-1,-1,-1/
      DATA (NHEL(I,  28),I=1,5) / 0,-1,-1,-1, 1/
      DATA (NHEL(I,  29),I=1,5) / 0,-1, 1, 1,-1/
      DATA (NHEL(I,  30),I=1,5) / 0,-1, 1, 1, 1/
      DATA (NHEL(I,  31),I=1,5) / 0,-1, 1,-1,-1/
      DATA (NHEL(I,  32),I=1,5) / 0,-1, 1,-1, 1/
      DATA (NHEL(I,  33),I=1,5) / 1, 1,-1, 1,-1/
      DATA (NHEL(I,  34),I=1,5) / 1, 1,-1, 1, 1/
      DATA (NHEL(I,  35),I=1,5) / 1, 1,-1,-1,-1/
      DATA (NHEL(I,  36),I=1,5) / 1, 1,-1,-1, 1/
      DATA (NHEL(I,  37),I=1,5) / 1, 1, 1, 1,-1/
      DATA (NHEL(I,  38),I=1,5) / 1, 1, 1, 1, 1/
      DATA (NHEL(I,  39),I=1,5) / 1, 1, 1,-1,-1/
      DATA (NHEL(I,  40),I=1,5) / 1, 1, 1,-1, 1/
      DATA (NHEL(I,  41),I=1,5) / 1,-1,-1, 1,-1/
      DATA (NHEL(I,  42),I=1,5) / 1,-1,-1, 1, 1/
      DATA (NHEL(I,  43),I=1,5) / 1,-1,-1,-1,-1/
      DATA (NHEL(I,  44),I=1,5) / 1,-1,-1,-1, 1/
      DATA (NHEL(I,  45),I=1,5) / 1,-1, 1, 1,-1/
      DATA (NHEL(I,  46),I=1,5) / 1,-1, 1, 1, 1/
      DATA (NHEL(I,  47),I=1,5) / 1,-1, 1,-1,-1/
      DATA (NHEL(I,  48),I=1,5) / 1,-1, 1,-1, 1/
